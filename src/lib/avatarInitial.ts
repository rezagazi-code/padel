/**
 * حرف اول آواتار، همیشه به لاتین: وقتی بازیکنی عکس ندارد، به‌جای حرف
 * فارسی اسمش، معادل لاتین همان حرف نشان داده می‌شود (رضا → R، محمد → M).
 * اسم لاتین همان‌طور که هست برمی‌گردد (فقط بزرگ می‌شود)؛ برای اسم خالی
 * یا حرف ناشناخته '?' برمی‌گردد تا آواتار همیشه لاتین بماند.
 */
const FA_TO_LATIN_INITIAL: Record<string, string> = {
  'ا': 'A', 'آ': 'A', 'ء': 'A', 'أ': 'A', 'إ': 'A',
  'ب': 'B',
  'پ': 'P',
  'ت': 'T',
  'ث': 'S',
  'ج': 'J',
  'چ': 'C',
  'ح': 'H',
  'خ': 'K',
  'د': 'D',
  'ذ': 'Z',
  'ر': 'R',
  'ز': 'Z',
  'ژ': 'Z',
  'س': 'S',
  'ش': 'S',
  'ص': 'S',
  'ض': 'Z',
  'ط': 'T',
  'ظ': 'Z',
  'ع': 'A',
  'غ': 'G',
  'ف': 'F',
  'ق': 'Q',
  'ک': 'K', 'ك': 'K',
  'گ': 'G',
  'ل': 'L',
  'م': 'M',
  'ن': 'N',
  'و': 'V',
  'ه': 'H',
  'ی': 'Y', 'ي': 'Y',
};

export function avatarInitial(name?: string | null): string {
  const first = (name ?? '').trim().charAt(0);
  if (!first) return '?';
  if (/[a-zA-Z0-9]/.test(first)) return first.toUpperCase();
  return FA_TO_LATIN_INITIAL[first] ?? '?';
}
